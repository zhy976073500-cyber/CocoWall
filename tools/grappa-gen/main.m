/* grappa-gen — build-host Grappa token generator for CocoWall.
 *
 * Runs on the macOS build host during CI (see the "Generate bundled
 * Grappa token" pre-build script in project.yml) and mints one
 * AirTraffic "Grappa" client token. Two routes, in order:
 *
 *   1. Framework C entry (the macOS home route): dlsym
 *      ALGetGrappaToken in every loaded AirTraffic framework and in
 *      RTLD_DEFAULT, called with the (1,0,1) triple. The Vellum /
 *      airlift dissection records (research/write-path.md) name this
 *      entry, exported by AirTrafficHost, as how a Mac sync host
 *      mints its token.
 *   2. Session class (the iOS route, kept as fallback):
 *      ATGrappaSession initWithType: 1 (host session) +
 *      establishHostSessionWithDeviceInfo:clientRequestData:.
 *      Run #29 proved this class does not exist in macOS's
 *      AirTrafficHost (it lives in iOS's AirTrafficDevice), so on
 *      this host route 2 is expected to stay unreachable — it is
 *      kept, with its MARK chain, for completeness.
 *
 * The host-session path needs CoreFP, which is present on macOS but
 * absent on iOS (the on-device probes in build #25 proved the
 * runtime route dead on the phone: ATGrappaDeviceInfo returns nil
 * and establish fails with ATError 0). The token is minted for the
 * (version=1, deviceType=0,
 * protocolVersion=1) triple; it is not bound to a device or a session
 * — the device-side daemon verifies the token body itself (a CoreFP
 * signature structure). Sage approved shipping a token generated by
 * our own build pipeline as the in-app helper's last-resort fallback;
 * the runtime paths in the helper always run first.
 *
 * Contract:
 *   stdout: exactly one line — the token as lowercase hex — on success.
 *   stderr: step-by-step diagnostics (never the token itself).
 *   argv[1] (optional): path of a diagnostics file. Every diagnostic
 *   line is ALSO written there with raw write()+fsync, and numbered
 *   "MARK n" lines bracket every framework interaction. Run #26 died
 *   with SIGKILL and zero captured output; with this file the last
 *   MARK line shows exactly how far the process got even if it is
 *   killed externally. MARK 0 is emitted as the first statement of
 *   main(), before any framework call.
 *   exit 0: token produced.
 *   exit 2: neither AirTraffic framework could be loaded.
 *   exit 3: no framework token entry produced a token and the
 *           ATGrappaSession class was not found (or is incomplete).
 *   exit 4: every host-session establish attempt returned an NSError.
 *   exit 5: a session was created but produced no/empty token data.
 *   exit 6: host session object could not be created.
 *   exit 70: an NSException escaped (details on stderr).
 *
 * The generated token is a build product: it must never be committed
 * to git (see .gitignore). This tool only writes to stdout/stderr.
 */

#import <Foundation/Foundation.h>
#import <dlfcn.h>
#import <fcntl.h>
#import <objc/message.h>
#import <objc/runtime.h>
#import <stdarg.h>
#import <stdio.h>
#import <string.h>
#import <unistd.h>

/* Signature of the framework-exported device-info function. */
typedef id (*CWGrappaDeviceInfoFn)(void);

/* Signature of the framework-exported token entry point, shared with
 * the in-app helper (Sources/App/GrappaHelper.m). */
typedef int (*CWGrappaTokenFn)(uint32_t, uint32_t, uint32_t,
                               uint8_t *, size_t, size_t *,
                               char *, size_t);

/* Diagnostics file descriptor (argv[1]); -1 when not provided. Lines
 * are written with raw write()+fsync so they survive an external
 * SIGKILL of this process — stdio buffering must never be the reason
 * a dead run leaves no evidence again. */
static int gDiagFd = -1;

static void emitLine(const char *utf8) {
    fprintf(stderr, "grappa-gen: %s\n", utf8);
    fflush(stderr);
    if (gDiagFd >= 0) {
        (void)!write(gDiagFd, utf8, strlen(utf8));
        (void)!write(gDiagFd, "\n", 1);
        fsync(gDiagFd);
    }
}

static void diag(NSString *format, ...) {
    va_list args;
    va_start(args, format);
    NSString *line = [[NSString alloc] initWithFormat:format arguments:args];
    va_end(args);
    emitLine(line.UTF8String ?: "?");
}

/* Pure-C marker: safe to call before @autoreleasepool / Foundation
 * setup. Used for the numbered MARK lines that bracket every risky
 * call so a killed run still shows its last completed step. */
static void markf(const char *format, ...) {
    char buf[1200];
    va_list args;
    va_start(args, format);
    vsnprintf(buf, sizeof(buf), format, args);
    va_end(args);
    emitLine(buf);
}

static NSString *hexString(NSData *data) {
    static const char digits[] = "0123456789abcdef";
    const uint8_t *bytes = (const uint8_t *)data.bytes;
    NSMutableString *hex = [NSMutableString stringWithCapacity:data.length * 2];
    for (NSUInteger i = 0; i < data.length; i++) {
        char pair[3] = { digits[bytes[i] >> 4], digits[bytes[i] & 0x0F], '\0' };
        [hex appendFormat:@"%s", pair];
    }
    return hex;
}

int main(int argc, char *argv[]) {
    if (argc > 1 && argv[1] != NULL && argv[1][0] != '\0') {
        gDiagFd = open(argv[1], O_WRONLY | O_CREAT | O_APPEND, 0644);
    }
    /* First statement of main(): if the diag file lacks even this
     * line, the process died in dyld / exec (signature class), which
     * is a different failure family from dying inside a framework. */
    markf("MARK 0: main() entered (pid=%d, diagFd=%d)", (int)getpid(), gDiagFd);
    @autoreleasepool {
        markf("MARK 1: autoreleasepool entered");
        @try {
            /* ── Load both AirTraffic frameworks (no short-circuit) ── */
            static const char *paths[2] = {
                "/System/Library/PrivateFrameworks/AirTrafficDevice.framework/AirTrafficDevice",
                "/System/Library/PrivateFrameworks/AirTrafficHost.framework/AirTrafficHost",
            };
            static const char *names[2] = { "AirTrafficDevice", "AirTrafficHost" };
            void *handles[2] = { NULL, NULL };
            unsigned loaded = 0;
            for (unsigned i = 0; i < 2; i++) {
                markf("MARK 2.%u: before dlopen %s", i, names[i]);
                dlerror(); /* clear */
                handles[i] = dlopen(paths[i], RTLD_NOW);
                markf("MARK 3.%u: after dlopen %s -> %s", i, names[i],
                      handles[i] != NULL ? "handle OK" : "NULL");
                if (handles[i] != NULL) {
                    loaded++;
                    diag(@"dlopen %s -> OK", names[i]);
                } else {
                    const char *err = dlerror();
                    diag(@"dlopen %s -> FAIL (%s)", names[i], err ?: "unknown error");
                }
            }
            if (loaded == 0) {
                diag(@"FATAL: neither AirTraffic framework could be loaded on this host");
                return 2;
            }

            /* ── Token + provenance, filled by whichever route wins ─ */
            int result = 4;
            NSData *token = nil;
            NSString *tokenSource = nil;

            /* ── Forensics: the Grappa surface of AirTrafficHost ────
             * Evidence only; nothing branches on it. Run #29 proved
             * the session class is absent from the macOS Host image,
             * so this class list maps what Grappa machinery that
             * image actually carries. (The ATGrappaDeviceInfo half of
             * the evidence is the per-framework probe inside the
             * route-2 candidate step below.) */
            markf("MARK 30: before Grappa class scan (AirTrafficHost image)");
            {
                unsigned int classCount = 0;
                const char **classNames =
                    objc_copyClassNamesForImage(paths[1], &classCount);
                NSMutableArray<NSString *> *grappaClasses = [NSMutableArray array];
                for (unsigned int c = 0; c < classCount; c++) {
                    NSString *name = classNames[c] ? @(classNames[c]) : @"";
                    if ([name rangeOfString:@"Grappa" options:NSCaseInsensitiveSearch]
                            .location != NSNotFound) {
                        [grappaClasses addObject:name];
                    }
                }
                free(classNames);
                diag(@"AirTrafficHost image Grappa classes (%lu of %u): %@",
                     (unsigned long)grappaClasses.count, classCount,
                     [grappaClasses componentsJoinedByString:@","]);
            }
            markf("MARK 31: after Grappa class scan");

            /* ── Route 1: framework ALGetGrappaToken ────────────────
             * Probe the C entry in every loaded framework, then in
             * RTLD_DEFAULT; call the first hit with the (1,0,1)
             * triple and the helper's shared signature. */
            void *tokenHandles[3] = { handles[0], handles[1], RTLD_DEFAULT };
            static const char *tokenHandleNames[3] = {
                "AirTrafficDevice", "AirTrafficHost", "RTLD_DEFAULT",
            };
            for (unsigned i = 0; i < 3 && token == nil; i++) {
                if (tokenHandles[i] == NULL) {
                    continue;
                }
                markf("MARK 32.%u: before dlsym ALGetGrappaToken (%s)",
                      i, tokenHandleNames[i]);
                dlerror(); /* clear */
                CWGrappaTokenFn tokenFn =
                    (CWGrappaTokenFn)dlsym(tokenHandles[i], "ALGetGrappaToken");
                markf("MARK 33.%u: after dlsym ALGetGrappaToken (%s) -> %s",
                      i, tokenHandleNames[i], tokenFn != NULL ? "FOUND" : "NOT FOUND");
                if (tokenFn == NULL) {
                    const char *err = dlerror();
                    diag(@"%s symbol ALGetGrappaToken -> NOT FOUND (%s)",
                         tokenHandleNames[i], err ?: "no dlerror");
                    continue;
                }
                diag(@"%s symbol ALGetGrappaToken -> FOUND, calling it with triple (1,0,1)",
                     tokenHandleNames[i]);
                uint8_t fwBuf[512];
                size_t fwLen = 0;
                char fwDiag[512] = { 0 };
                int fwRc = -1;
                markf("MARK 34.%u: before ALGetGrappaToken call (%s)",
                      i, tokenHandleNames[i]);
                @try {
                    fwRc = tokenFn(1, 0, 1, fwBuf, sizeof(fwBuf), &fwLen,
                                   fwDiag, sizeof(fwDiag));
                } @catch (NSException *e) {
                    diag(@"%s ALGetGrappaToken raised %@: %@",
                         tokenHandleNames[i], e.name ?: @"?", e.reason ?: @"");
                }
                markf("MARK 35.%u: after ALGetGrappaToken call (%s) -> rc=%d len=%lu",
                      i, tokenHandleNames[i], fwRc, (unsigned long)fwLen);
                diag(@"%s ALGetGrappaToken call rc=%d len=%lu diag=%s",
                     tokenHandleNames[i], fwRc, (unsigned long)fwLen, fwDiag);
                if (fwRc == 0 && fwLen > 0) {
                    token = [NSData dataWithBytes:fwBuf length:fwLen];
                    tokenSource = [NSString stringWithFormat:@"%s ALGetGrappaToken",
                                                             tokenHandleNames[i]];
                    result = 0;
                }
            }
            if (token != nil) {
                diag(@"framework ALGetGrappaToken produced the token; "
                     @"ATGrappaSession route skipped");
            }

            /* ── Route 2 (fallback): ATGrappaSession host session ── */
            if (token == nil) {
            /* ── Candidate device-info dictionaries, helper order ──── */
            NSMutableArray<NSDictionary *> *candidates = [NSMutableArray array];
            NSMutableArray<NSString *> *candidateSources = [NSMutableArray array];
            NSMutableSet<NSString *> *seen = [NSMutableSet set];
            void (^addCandidate)(NSDictionary *, NSString *) =
                ^(NSDictionary *dict, NSString *source) {
                    NSString *signature = [dict description] ?: @"";
                    if (![seen containsObject:signature]) {
                        [seen addObject:signature];
                        [candidates addObject:dict];
                        [candidateSources addObject:source];
                    }
                };

            for (unsigned i = 0; i < 2; i++) {
                if (handles[i] == NULL) {
                    continue;
                }
                dlerror(); /* clear */
                CWGrappaDeviceInfoFn infoFn =
                    (CWGrappaDeviceInfoFn)dlsym(handles[i], "ATGrappaDeviceInfo");
                if (infoFn == NULL) {
                    const char *err = dlerror();
                    diag(@"%s symbol ATGrappaDeviceInfo -> NOT FOUND (%s)",
                         names[i], err ?: "no dlerror");
                    continue;
                }
                diag(@"%s symbol ATGrappaDeviceInfo -> FOUND, calling it", names[i]);
                markf("MARK 4.%u: before calling ATGrappaDeviceInfo (%s)", i, names[i]);
                id produced = nil;
                @try {
                    produced = infoFn();
                } @catch (NSException *e) {
                    diag(@"%s ATGrappaDeviceInfo raised %@: %@",
                         names[i], e.name ?: @"?", e.reason ?: @"");
                }
                markf("MARK 5.%u: after ATGrappaDeviceInfo (%s) -> %s", i, names[i],
                      produced != nil ? "non-nil" : "nil");
                if ([produced isKindOfClass:[NSDictionary class]]) {
                    NSDictionary *dict = (NSDictionary *)produced;
                    diag(@"%s ATGrappaDeviceInfo -> dictionary version=%@ deviceType=%@ protocolVersion=%@",
                         names[i],
                         dict[@"version"] ?: @"<absent>",
                         dict[@"deviceType"] ?: @"<absent>",
                         dict[@"protocolVersion"] ?: @"<absent>");
                    addCandidate(dict,
                                 [NSString stringWithFormat:@"%s ATGrappaDeviceInfo", names[i]]);
                } else if (produced == nil) {
                    diag(@"%s ATGrappaDeviceInfo -> returned nil", names[i]);
                } else {
                    diag(@"%s ATGrappaDeviceInfo -> returned non-dictionary class=%@",
                         names[i], NSStringFromClass([produced class]));
                }
            }
            /* The triple this tool exists to mint for. */
            addCandidate(@{ @"version" : @1, @"deviceType" : @0, @"protocolVersion" : @1 },
                         @"literal triple (1,0,1)");
            diag(@"device-info candidates: %lu", (unsigned long)candidates.count);

            /* ── ATGrappaSession host session ──────────────────────── */
            markf("MARK 6: before objc_getClass(ATGrappaSession)");
            Class sessionClass = objc_getClass("ATGrappaSession");
            markf("MARK 7: after objc_getClass(ATGrappaSession) -> %s",
                  sessionClass != Nil ? "FOUND" : "NOT FOUND");
            if (sessionClass == Nil) {
                diag(@"FATAL: class ATGrappaSession -> NOT FOUND");
                return 3;
            }
            diag(@"class ATGrappaSession -> FOUND (image: %s)",
                 class_getImageName(sessionClass) ?: "<unknown>");
            SEL initSel = sel_registerName("initWithType:");
            SEL establishSel =
                sel_registerName("establishHostSessionWithDeviceInfo:clientRequestData:");
            if (![sessionClass instancesRespondToSelector:initSel] ||
                ![sessionClass instancesRespondToSelector:establishSel]) {
                diag(@"FATAL: ATGrappaSession lacks initWithType: or "
                     @"establishHostSessionWithDeviceInfo:clientRequestData:");
                return 3;
            }

            for (NSUInteger c = 0; c < candidates.count && token == nil; c++) {
                NSDictionary *info = candidates[c];
                diag(@"host session attempt with info from %@ (version=%@ deviceType=%@ protocolVersion=%@)",
                     candidateSources[c],
                     info[@"version"] ?: @"<absent>",
                     info[@"deviceType"] ?: @"<absent>",
                     info[@"protocolVersion"] ?: @"<absent>");

                markf("MARK 8.%lu: before alloc/initWithType:1 (candidate %lu)",
                      (unsigned long)c, (unsigned long)c);
                id session = nil;
                @try {
                    id alloced = ((id (*)(id, SEL))objc_msgSend)((id)sessionClass,
                                                                 sel_registerName("alloc"));
                    /* type 1 = host session */
                    session = ((id (*)(id, SEL, unsigned int))objc_msgSend)(alloced, initSel, 1);
                } @catch (NSException *e) {
                    diag(@"initWithType: raised %@: %@", e.name ?: @"?", e.reason ?: @"");
                }
                if (session == nil) {
                    diag(@"host session (initWithType: 1) -> nil");
                    result = 6;
                    continue;
                }

                markf("MARK 9.%lu: before establishHostSessionWithDeviceInfo (candidate %lu)",
                      (unsigned long)c, (unsigned long)c);
                NSData *produced = nil;
                NSError *establishError = nil;
                @try {
                    establishError = ((NSError * (*)(id, SEL, id, NSData **))objc_msgSend)(
                        session, establishSel, info, &produced);
                } @catch (NSException *e) {
                    diag(@"establishHostSession raised %@: %@", e.name ?: @"?", e.reason ?: @"");
                    result = 4;
                    continue;
                }
                markf("MARK 10.%lu: after establish -> error=%s producedLen=%lu",
                      (unsigned long)c,
                      establishError != nil ? "yes" : "no",
                      (unsigned long)([produced isKindOfClass:[NSData class]]
                                           ? ((NSData *)produced).length
                                           : 0));
                if (establishError != nil) {
                    diag(@"establishHostSession NSError domain=%@ code=%ld desc=%@",
                         establishError.domain ?: @"?",
                         (long)establishError.code,
                         establishError.localizedDescription ?: @"");
                    result = 4;
                    continue;
                }
                if (![produced isKindOfClass:[NSData class]] || produced.length == 0) {
                    diag(@"establishHostSession returned no data (class=%@)",
                         produced ? NSStringFromClass([produced class]) : @"nil");
                    result = 5;
                    continue;
                }
                token = produced;
                tokenSource = [NSString stringWithFormat:
                    @"host session (info from %@)", candidateSources[c]];
                result = 0;
            }
            } /* if (token == nil) — end of route 2 */
            if (token == nil) {
                diag(@"FATAL: no route produced a token (last rc=%d)", result);
                return result;
            }

            markf("MARK 11: token produced (%lu bytes) - writing hex to stdout",
                  (unsigned long)token.length);
            NSString *hex = hexString(token);
            diag(@"token minted via %@ (%lu bytes, prefix 0x%02x%02x)",
                 tokenSource,
                 (unsigned long)token.length,
                 token.length > 0 ? ((const uint8_t *)token.bytes)[0] : 0,
                 token.length > 1 ? ((const uint8_t *)token.bytes)[1] : 0);
            /* stdout carries ONLY the hex line — build scripts parse it. */
            fprintf(stdout, "%s\n", hex.UTF8String);
            fflush(stdout);
            return 0;
        } @catch (NSException *e) {
            diag(@"FATAL: NSException %@: %@", e.name ?: @"?", e.reason ?: @"");
            return 70;
        }
    }
}
