/* grappa-gen — build-host Grappa token generator for CocoWall.
 *
 * Runs on the macOS build host during CI (see the "Generate bundled
 * Grappa token" pre-build script in project.yml) and mints one
 * AirTraffic "Grappa" client token through the same host-session path
 * the in-app helper (Sources/App/GrappaHelper.m) uses:
 *
 *   dlopen AirTrafficDevice -> AirTrafficHost
 *   ATGrappaSession initWithType: 1 (host session)
 *   establishHostSessionWithDeviceInfo:clientRequestData:
 *
 * That path needs CoreFP, which is present on macOS but absent on iOS
 * (the on-device probes in build #25 proved the runtime route dead on
 * the phone: ATGrappaDeviceInfo returns nil and establish fails with
 * ATError 0). The token is minted for the (version=1, deviceType=0,
 * protocolVersion=1) triple; it is not bound to a device or a session
 * — the device-side daemon verifies the token body itself (a CoreFP
 * signature structure). Sage approved shipping a token generated by
 * our own build pipeline as the in-app helper's last-resort fallback;
 * the runtime paths in the helper always run first.
 *
 * Contract:
 *   stdout: exactly one line — the token as lowercase hex — on success.
 *   stderr: step-by-step diagnostics (never the token itself).
 *   exit 0: token produced.
 *   exit 2: neither AirTraffic framework could be loaded.
 *   exit 3: ATGrappaSession class not found.
 *   exit 4: every host-session establish attempt returned an NSError.
 *   exit 5: a session was created but produced no/empty token data.
 *   exit 6: host session object could not be created.
 *   exit 70: an NSException escaped (details on stderr).
 *
 * The generated token is a build product: it must never be committed
 * to git (see .gitignore). This tool only writes to stdout/stderr.
 */

#import <Foundation/Foundation.h>
#import <dlfcn.h>
#import <objc/message.h>
#import <objc/runtime.h>
#import <stdarg.h>
#import <stdio.h>
#import <string.h>

/* Signature of the framework-exported device-info function. */
typedef id (*CWGrappaDeviceInfoFn)(void);

static void diag(NSString *format, ...) {
    va_list args;
    va_start(args, format);
    NSString *line = [[NSString alloc] initWithFormat:format arguments:args];
    va_end(args);
    fprintf(stderr, "grappa-gen: %s\n", line.UTF8String ?: "?");
    fflush(stderr);
}

static NSString *hexString(NSData *data) {
    static const char digits[] = "0123456789abcdef";
    const uint8_t *bytes = (const uint8_t *)data.bytes;
    NSMutableString *hex = [NSMutableString stringWithCapacity:data.length * 2];
    for (NSUInteger i = 0; i < data.length; i++) {
        char pair[3] = { digits[bytes[i] >> 4], digits[bytes[i] & 0x0F], '\0' };
        [hex appendFormat:@"%s", pair];
    }
    return hex;
}

int main(int argc, char *argv[]) {
    (void)argc;
    (void)argv;
    @autoreleasepool {
        @try {
            /* ── Load both AirTraffic frameworks (no short-circuit) ── */
            static const char *paths[2] = {
                "/System/Library/PrivateFrameworks/AirTrafficDevice.framework/AirTrafficDevice",
                "/System/Library/PrivateFrameworks/AirTrafficHost.framework/AirTrafficHost",
            };
            static const char *names[2] = { "AirTrafficDevice", "AirTrafficHost" };
            void *handles[2] = { NULL, NULL };
            unsigned loaded = 0;
            for (unsigned i = 0; i < 2; i++) {
                dlerror(); /* clear */
                handles[i] = dlopen(paths[i], RTLD_NOW);
                if (handles[i] != NULL) {
                    loaded++;
                    diag(@"dlopen %s -> OK", names[i]);
                } else {
                    const char *err = dlerror();
                    diag(@"dlopen %s -> FAIL (%s)", names[i], err ?: "unknown error");
                }
            }
            if (loaded == 0) {
                diag(@"FATAL: neither AirTraffic framework could be loaded on this host");
                return 2;
            }

            /* ── Candidate device-info dictionaries, helper order ──── */
            NSMutableArray<NSDictionary *> *candidates = [NSMutableArray array];
            NSMutableArray<NSString *> *candidateSources = [NSMutableArray array];
            NSMutableSet<NSString *> *seen = [NSMutableSet set];
            void (^addCandidate)(NSDictionary *, NSString *) =
                ^(NSDictionary *dict, NSString *source) {
                    NSString *signature = [dict description] ?: @"";
                    if (![seen containsObject:signature]) {
                        [seen addObject:signature];
                        [candidates addObject:dict];
                        [candidateSources addObject:source];
                    }
                };

            for (unsigned i = 0; i < 2; i++) {
                if (handles[i] == NULL) {
                    continue;
                }
                dlerror(); /* clear */
                CWGrappaDeviceInfoFn infoFn =
                    (CWGrappaDeviceInfoFn)dlsym(handles[i], "ATGrappaDeviceInfo");
                if (infoFn == NULL) {
                    const char *err = dlerror();
                    diag(@"%s symbol ATGrappaDeviceInfo -> NOT FOUND (%s)",
                         names[i], err ?: "no dlerror");
                    continue;
                }
                diag(@"%s symbol ATGrappaDeviceInfo -> FOUND, calling it", names[i]);
                id produced = nil;
                @try {
                    produced = infoFn();
                } @catch (NSException *e) {
                    diag(@"%s ATGrappaDeviceInfo raised %@: %@",
                         names[i], e.name ?: @"?", e.reason ?: @"");
                }
                if ([produced isKindOfClass:[NSDictionary class]]) {
                    NSDictionary *dict = (NSDictionary *)produced;
                    diag(@"%s ATGrappaDeviceInfo -> dictionary version=%@ deviceType=%@ protocolVersion=%@",
                         names[i],
                         dict[@"version"] ?: @"<absent>",
                         dict[@"deviceType"] ?: @"<absent>",
                         dict[@"protocolVersion"] ?: @"<absent>");
                    addCandidate(dict,
                                 [NSString stringWithFormat:@"%s ATGrappaDeviceInfo", names[i]]);
                } else if (produced == nil) {
                    diag(@"%s ATGrappaDeviceInfo -> returned nil", names[i]);
                } else {
                    diag(@"%s ATGrappaDeviceInfo -> returned non-dictionary class=%@",
                         names[i], NSStringFromClass([produced class]));
                }
            }
            /* The triple this tool exists to mint for. */
            addCandidate(@{ @"version" : @1, @"deviceType" : @0, @"protocolVersion" : @1 },
                         @"literal triple (1,0,1)");
            diag(@"device-info candidates: %lu", (unsigned long)candidates.count);

            /* ── ATGrappaSession host session ──────────────────────── */
            Class sessionClass = objc_getClass("ATGrappaSession");
            if (sessionClass == Nil) {
                diag(@"FATAL: class ATGrappaSession -> NOT FOUND");
                return 3;
            }
            diag(@"class ATGrappaSession -> FOUND (image: %s)",
                 class_getImageName(sessionClass) ?: "<unknown>");
            SEL initSel = sel_registerName("initWithType:");
            SEL establishSel =
                sel_registerName("establishHostSessionWithDeviceInfo:clientRequestData:");
            if (![sessionClass instancesRespondToSelector:initSel] ||
                ![sessionClass instancesRespondToSelector:establishSel]) {
                diag(@"FATAL: ATGrappaSession lacks initWithType: or "
                     @"establishHostSessionWithDeviceInfo:clientRequestData:");
                return 3;
            }

            int result = 4;
            NSData *token = nil;
            NSString *tokenSource = nil;
            for (NSUInteger c = 0; c < candidates.count && token == nil; c++) {
                NSDictionary *info = candidates[c];
                diag(@"host session attempt with info from %@ (version=%@ deviceType=%@ protocolVersion=%@)",
                     candidateSources[c],
                     info[@"version"] ?: @"<absent>",
                     info[@"deviceType"] ?: @"<absent>",
                     info[@"protocolVersion"] ?: @"<absent>");

                id session = nil;
                @try {
                    id alloced = ((id (*)(id, SEL))objc_msgSend)((id)sessionClass,
                                                                 sel_registerName("alloc"));
                    /* type 1 = host session */
                    session = ((id (*)(id, SEL, unsigned int))objc_msgSend)(alloced, initSel, 1);
                } @catch (NSException *e) {
                    diag(@"initWithType: raised %@: %@", e.name ?: @"?", e.reason ?: @"");
                }
                if (session == nil) {
                    diag(@"host session (initWithType: 1) -> nil");
                    result = 6;
                    continue;
                }

                NSData *produced = nil;
                NSError *establishError = nil;
                @try {
                    establishError = ((NSError * (*)(id, SEL, id, NSData **))objc_msgSend)(
                        session, establishSel, info, &produced);
                } @catch (NSException *e) {
                    diag(@"establishHostSession raised %@: %@", e.name ?: @"?", e.reason ?: @"");
                    result = 4;
                    continue;
                }
                if (establishError != nil) {
                    diag(@"establishHostSession NSError domain=%@ code=%ld desc=%@",
                         establishError.domain ?: @"?",
                         (long)establishError.code,
                         establishError.localizedDescription ?: @"");
                    result = 4;
                    continue;
                }
                if (![produced isKindOfClass:[NSData class]] || produced.length == 0) {
                    diag(@"establishHostSession returned no data (class=%@)",
                         produced ? NSStringFromClass([produced class]) : @"nil");
                    result = 5;
                    continue;
                }
                token = produced;
                tokenSource = candidateSources[c];
                result = 0;
            }
            if (token == nil) {
                diag(@"FATAL: no host-session attempt produced a token (last rc=%d)", result);
                return result;
            }

            NSString *hex = hexString(token);
            diag(@"token minted via host session with info from %@ (%lu bytes, prefix 0x%02x%02x)",
                 tokenSource,
                 (unsigned long)token.length,
                 token.length > 0 ? ((const uint8_t *)token.bytes)[0] : 0,
                 token.length > 1 ? ((const uint8_t *)token.bytes)[1] : 0);
            /* stdout carries ONLY the hex line — build scripts parse it. */
            fprintf(stdout, "%s\n", hex.UTF8String);
            fflush(stdout);
            return 0;
        } @catch (NSException *e) {
            diag(@"FATAL: NSException %@: %@", e.name ?: @"?", e.reason ?: @"");
            return 70;
        }
    }
}
